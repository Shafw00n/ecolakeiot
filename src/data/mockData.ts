export const GENERATE_TELEMETRY_HISTORY = (): SystemTelemetryHistory[] => {
  const times = ['00:00', '03:00', '06:00', '09:00', '12:00', '15:00', '18:00', '21:00'];
  return times.map((t, idx) => ({
    time: t,
    pH: parseFloat((7.2 + Math.sin(idx) * 0.25).toFixed(2)),
    DO: parseFloat((6.4 + Math.cos(idx * 0.8) * 0.6).toFixed(2)),
    turbidity: parseFloat((15.0 + Math.sin(idx * 1.5) * 3.5).toFixed(1)),
    temperature: parseFloat((25.5 + (idx > 3 && idx < 7 ? 2.5 : 0.5)).toFixed(1)),
    nitrate: parseFloat((1.3 - idx * 0.04).toFixed(2)),
    phosphate: parseFloat((0.2 - idx * 0.01).toFixed(2)),
  }));
};
